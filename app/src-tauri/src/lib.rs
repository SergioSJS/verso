fn note_out(t: verso_core::NoteText) -> NoteText {
    NoteText {
        path: t.path,
        lines: t.lines,
        html: t.html,
        properties: t
            .properties
            .into_iter()
            .map(|(key, value)| Property {
                key,
                value: match value {
                    verso_core::PropertyValue::Text(s) => PropertyValue::Text(s),
                    verso_core::PropertyValue::Number(s) => PropertyValue::Number(s),
                    verso_core::PropertyValue::Checkbox(b) => PropertyValue::Checkbox(b),
                    verso_core::PropertyValue::List(v) => PropertyValue::List(v),
                    verso_core::PropertyValue::Nested(s) => PropertyValue::Nested(s),
                    verso_core::PropertyValue::Empty => PropertyValue::Empty,
                },
            })
            .collect(),
        text: t.text,
        revision: t.revision,
        headings: t
            .headings
            .into_iter()
            .map(|h| Heading {
                level: h.level,
                text: h.text,
                line: h.line,
                col: h.col,
            })
            .collect(),
        blocks: t
            .blocks
            .into_iter()
            .map(|b| Block {
                id: b.id,
                line: b.line,
                col: b.col,
            })
            .collect(),
        stale: t.stale,
        unverified: t.unverified,
    }
}

/// Full-text search: every word must occur, accents and case ignored.
#[tauri::command]
#[specta::specta]
fn search(state: State<'_, App>, words: String, limit: u32) -> Result<Vec<Hit>, ContractError> {
    with(&state, |ws| {
        Ok(ws
            .search(&words, usize::try_from(limit.clamp(1, 200)).unwrap_or(20))?
            .into_iter()
            .map(|h| Hit {
                path: h.path,
                snippet: h.snippet,
            })
            .collect())
    })
}

