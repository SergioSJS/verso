/// What `verso://` answers to one request, apart from the transport: the
/// status, the headers, the body. Kept free of Tauri's types so the
/// rules are tested directly.
struct Served {
    status: u16,
    headers: Vec<(&'static str, String)>,
    body: Vec<u8>,
}

/// The policy every `verso://` response carries: whatever the file is,
/// a document made of it runs no script, submits no form and reaches
/// nothing but the folder's own files (SVG and HTML are active content;
/// review `docs/review/phase-2.md`, B1).
const FILE_CSP: &str = "sandbox; default-src 'none'; img-src verso: http://verso.localhost data:; media-src verso: http://verso.localhost; style-src 'unsafe-inline' verso: http://verso.localhost; font-src verso: http://verso.localhost data:";

/// The origins of the app's own pages, the only ones allowed to read a
/// response with `fetch` (the PDF reader): `tauri://localhost` on macOS
/// and Linux, `http(s)://tauri.localhost` on Windows.
fn is_app_origin(origin: &str) -> bool {
    matches!(
        origin,
        "tauri://localhost" | "http://tauri.localhost" | "https://tauri.localhost"
    )
}

fn serve(
    ws: Option<&mut Workspace>,
    requester: &str,
    relative: &str,
    origin: Option<&str>,
) -> Served {
    let mut headers = vec![
        ("Content-Security-Policy", FILE_CSP.to_owned()),
        ("X-Content-Type-Options", "nosniff".to_owned()),
        ("Cache-Control", "no-store".to_owned()),
    ];
    if let Some(o) = origin.filter(|o| is_app_origin(o)) {
        headers.push(("Access-Control-Allow-Origin", o.to_owned()));
        headers.push(("Vary", "Origin".to_owned()));
    }
    let refuse = |status: u16, why: &str, mut headers: Vec<(&'static str, String)>| {
        headers.push(("Content-Type", "text/plain; charset=utf-8".to_owned()));
        Served {
            status,
            headers,
            body: why.as_bytes().to_vec(),
        }
    };
    // A web page's view never reads the folder, whatever it asks for.
    if !is_app_view(requester) {
        return refuse(403, "not a view of this app", headers);
    }
    // A note's text crosses through `read_note`, with its revision;
    // never as a bare file.
    if relative.to_lowercase().ends_with(".md") {
        return refuse(403, "a note is read through read_note", headers);
    }
    let Some(ws) = ws else {
        return refuse(404, "no folder is open", headers);
    };
    // And judged again on the path as confinement reads it: `Nota.md/`
    // and `./Nota.md` name the note too.
    if ws
        .confined(relative)
        .is_ok_and(|key| key.to_lowercase().ends_with(".md"))
    {
        return refuse(403, "a note is read through read_note", headers);
    }
    match ws.read_file(relative) {
        Ok(bytes) => {
            headers.push(("Content-Type", mime_of(relative).to_owned()));
            Served {
                status: 200,
                headers,
                body: bytes,
            }
        }
        Err(e) => {
            let e = convert(e);
            let status = match e.kind {
                ErrorKind::NotFound | ErrorKind::Refused | ErrorKind::NoFolder => 404,
                _ => 500,
            };
            refuse(status, &e.message, headers)
        }
    }
}

/// `verso://localhost/<relative path>`: a file of the folder that is not
/// a note — an image an embed names, a PDF, an HTML page shown without
/// scripts — read through the core, so the only door to the disk stays
/// `verso-fs` (ADR 0026 rule 5) and every path is confined. Only the
/// app's own views are answered, and only their origin may read a
/// response from script.
fn serve_file<R: tauri::Runtime>(
    ctx: tauri::UriSchemeContext<'_, R>,
    request: tauri::http::Request<Vec<u8>>,
) -> tauri::http::Response<std::borrow::Cow<'static, [u8]>> {
    let relative = percent_decode(request.uri().path().trim_start_matches('/'));
    let origin = request
        .headers()
        .get("Origin")
        .and_then(|v| v.to_str().ok())
        .map(str::to_owned);
    let state = ctx.app_handle().state::<App>();
    let served = {
        let mut guard = lock(&state.session);
        serve(
            guard.as_mut().map(|s| &mut s.workspace),
            ctx.webview_label(),
            &relative,
            origin.as_deref(),
        )
    };
    let mut response = tauri::http::Response::builder().status(served.status);
    for (name, value) in &served.headers {
        response = response.header(*name, value);
    }
    response
        .body(std::borrow::Cow::Owned(served.body))
        .unwrap_or_else(|_| tauri::http::Response::new(std::borrow::Cow::Owned(Vec::new())))
}

/// Open the window and serve it until it closes.
pub fn run(initial_folder: Option<PathBuf>) -> Result<(), Box<dyn std::error::Error>> {
    let commands = commands();
    let initial_folder = initial_folder.map(|p| std::path::absolute(&p).unwrap_or(p));
    let builder = tauri::Builder::default();
    #[cfg(target_os = "macos")]
    let builder = builder.menu(app_menu).on_menu_event(|app, event| {
        if event.id() == QUIT {
            ask_windows_to_quit(app);
        }
    });
    builder
        .plugin(tauri_plugin_dialog::init())
        .plugin(navigation_guard())
        .register_uri_scheme_protocol("verso", serve_file)
        .manage(App::new(initial_folder))
        .invoke_handler(commands.invoke_handler())
        .build(context())?
        .run(on_event);
    Ok(())
}

/// A quit — ⌘Q, or the last window going — asks every window to save
/// its tabs first: each one saves, then closes itself, and the app exits
/// when none is left (the next request finds no window and goes through).
/// A page's own close handler never hears a quit, so without this a quit
/// lost what was typed since the last autosave. A window whose text could
/// not be saved stays open if the user keeps it.
fn on_event<R: tauri::Runtime>(app: &tauri::AppHandle<R>, event: tauri::RunEvent) {
    match event {
        tauri::RunEvent::ExitRequested {
            api, code: None, ..
        } if !app.webview_windows().is_empty() => {
            api.prevent_exit();
            ask_windows_to_quit(app);
        }
        #[cfg(target_os = "macos")]
        tauri::RunEvent::Opened { urls } => {
            if let Some(folder) = urls.iter().find_map(|u| u.to_file_path().ok()) {
                folder_handed(app, folder);
            }
        }
        _ => {}
    }
}

/// macOS hands the app a folder by an open event — `open -a Verso
/// <folder>`, which is how `verso <folder>` starts the installed app —
/// both when it launches the app and when the app is already running; the
/// folder never reaches the command line, and before this it was lost on
/// a running app (`docs/review/phase-2.md`, reading 3, finding 20). It
/// takes the command line's place: the main window, if it is up, is told
/// to open it (`open_initial`, after saving its tabs), and one that starts
/// later opens it at start-up. What is not a folder fails there, as a
/// command-line argument would. Built for tests on every platform, so
/// the Linux runs check it too; only macOS sends the event.
#[cfg(any(target_os = "macos", test))]
fn folder_handed<R: tauri::Runtime>(app: &tauri::AppHandle<R>, folder: PathBuf) {
    *lock(&app.state::<App>().initial_folder) = Some(folder);
    if let Some(main) = app.get_webview_window("main") {
        let _ = main.set_focus();
    }
    let _ = app.emit_to("main", "folder-handed", ());
}

/// Ask the app's own windows to save their tabs and close themselves;
/// with none left, exit. A window that shows a web page holds nothing to
/// save and never answers, so it is closed here: left open, it would keep
/// the app alive after its windows had gone.
fn ask_windows_to_quit<R: tauri::Runtime>(app: &tauri::AppHandle<R>) {
    let mut ours = false;
    for (label, window) in app.webview_windows() {
        if is_app_view(&label) {
            ours = true;
        } else {
            let _ = window.destroy();
        }
    }
    if ours {
        let _ = app.emit("quit-requested", ());
    } else {
        app.exit(0);
    }
}

/// The id of the app menu's own Quit item.
#[cfg(target_os = "macos")]
const QUIT: &str = "verso-quit";

/// The macOS menu bar: the system's own items, except Quit. The system's
/// Quit terminates the process without an event the app can answer (the
/// run loop goes from ready to exit), so what was typed since the last
/// autosave was lost; this Quit, on the same ⌘Q, asks the windows to save
/// first (`on_event`).
#[cfg(target_os = "macos")]
fn app_menu<R: tauri::Runtime>(app: &tauri::AppHandle<R>) -> tauri::Result<tauri::menu::Menu<R>> {
    use tauri::menu::{Menu, MenuItem, PredefinedMenuItem, Submenu};
    let quit = MenuItem::with_id(app, QUIT, "Quit Verso", true, Some("CmdOrCtrl+Q"))?;
    let verso = Submenu::with_items(
        app,
        "Verso",
        true,
        &[
            &PredefinedMenuItem::about(
                app,
                None,
                Some(tauri::menu::AboutMetadata {
                    // macOS shows "Version <version> (<short_version>)": the
                    // version, then the commit in parentheses as the build.
                    version: Some(env!("CARGO_PKG_VERSION").to_owned()),
                    short_version: Some(env!("VERSO_COMMIT").to_owned()),
                    ..Default::default()
                }),
            )?,
            &PredefinedMenuItem::separator(app)?,
            &PredefinedMenuItem::services(app, None)?,
            &PredefinedMenuItem::separator(app)?,
            &PredefinedMenuItem::hide(app, None)?,
            &PredefinedMenuItem::hide_others(app, None)?,
            &PredefinedMenuItem::show_all(app, None)?,
            &PredefinedMenuItem::separator(app)?,
            &quit,
        ],
    )?;
    let edit = Submenu::with_items(
        app,
        "Edit",
        true,
        &[
            &PredefinedMenuItem::undo(app, None)?,
            &PredefinedMenuItem::redo(app, None)?,
            &PredefinedMenuItem::separator(app)?,
            &PredefinedMenuItem::cut(app, None)?,
            &PredefinedMenuItem::copy(app, None)?,
            &PredefinedMenuItem::paste(app, None)?,
            &PredefinedMenuItem::select_all(app, None)?,
        ],
    )?;
    let view = Submenu::with_items(
        app,
        "View",
        true,
        &[&PredefinedMenuItem::fullscreen(app, None)?],
    )?;
    let window = Submenu::with_items(
        app,
        "Window",
        true,
        &[
            &PredefinedMenuItem::minimize(app, None)?,
            &PredefinedMenuItem::maximize(app, None)?,
            &PredefinedMenuItem::separator(app)?,
            &PredefinedMenuItem::close_window(app, None)?,
        ],
    )?;
    Menu::with_items(app, &[&verso, &edit, &view, &window])
}

