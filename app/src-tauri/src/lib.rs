pub struct App {
    /// Notes popped out to windows of their own: window label → note.
    pub popouts: Mutex<std::collections::HashMap<String, String>>,
    /// Web pages inside windows: web view label → the window that opened
    /// it, which alone may move, hide, steer or close it.
    pub web_views: Mutex<std::collections::HashMap<String, String>>,
    /// The folder handed to the app from outside — named on the command
    /// line (`verso-app <folder>`) or, on macOS, sent by an open event
    /// (`folder_handed`) — opened once by `open_initial`: a path at the
    /// entry edge, on this side.
    initial_folder: Mutex<std::collections::VecDeque<PathBuf>>,
    /// Markdown files handed to the app (ADR 0114 item 6) and not yet
    /// opened by the loose-files window: paths at the entry edge.
    initial_file: Mutex<std::collections::VecDeque<PathBuf>>,
    /// The loose-files window (ADR 0114 item 7 iii, Q1): the one window
    /// whose tabs are files opened without a folder — picked or made for a
    /// file before it shows one, and known to the service once it does.
    loose_window: Mutex<Option<String>>,
    /// The folders of servers the windows showed when the app quit, waiting
    /// for a window to open them (`session::restore`): address and folder.
    /// `open_initial` takes them after the folders of this computer.
    initial_server: Mutex<std::collections::VecDeque<(String, String)>>,
    /// The app is quitting (⌘Q, the updater's restart): the windows that
    /// close with it are not windows the person closed, and the set the
    /// next start reopens keeps them (`session`).
    quitting: std::sync::atomic::AtomicBool,
    /// Windows handed a server's folder that could not be opened (the
    /// server is down for a moment, as when an update restarts both): the
    /// window label → the folder's key. The key stays in the set the next
    /// start reopens until the person closes the window (`session`).
    pub(crate) pending_servers: Mutex<std::collections::HashMap<String, String>>,
    /// Windows told a folder (`folder_handed`) and not done opening it:
    /// one is not handed another while it installs the first.
    opening: Mutex<std::collections::HashSet<String>>,
    /// The open folders and which window shows each (ADR 0065), apart
    /// from Tauri: the same service `verso serve` holds (ADR 0073 item 2).
    /// The tests give it a temporary index directory, so that a test run
    /// never writes into the user's.
    pub(crate) service: Arc<Service>,
    /// The windows that show a folder of a server: label → connection.
    pub(crate) remotes: Mutex<std::collections::HashMap<String, Arc<remote::Remote>>>,
    /// The folders that sync with a server, by key: their tasks (ADR 0079).
    pub(crate) syncs: Mutex<std::collections::HashMap<String, Arc<sync::Syncer>>>,
    /// The system's keychain, where the secrets of a cloud are kept (ADR
    /// 0104 item 14).
    pub(crate) secrets: Arc<dyn secrets::Secrets>,
    /// A cloud just checked and not yet started, by folder key.
    pub(crate) pending_clouds: cloud::Pending,
    /// Origins (`scheme://host[:port]`) of embedded pages the user
    /// approved by hand, mirrored from the window's settings. The gate in
    /// the window is what asks, and this list is its record on this side.
    /// An app view navigates to the web only to `framed_origins` below
    /// (ADR 0056, revised 2026-10-15).
    embed_origins: Mutex<std::collections::HashSet<String>>,
    /// What the frameability check found, by the origin it was asked
    /// about, for the session (ADR 0056, revised 2026-10-15).
    frame_verdicts: Mutex<std::collections::HashMap<String, bool>>,
    /// The origins a page judged frameable visits (its own, and where its
    /// redirects end): the only web origins an app view's frame may load.
    framed_origins: Mutex<std::collections::HashSet<String>>,
    /// The folders behind the menu's "Open Recent" items, in the order
    /// the menu shows: item `verso-recent-<i>` opens `menu_recents[i]`.
    /// Paths at the edge, on this side; they never cross to the UI. The
    /// menu is macOS's; elsewhere the field would sit unread.
    #[cfg(target_os = "macos")]
    menu_recents: Mutex<Vec<PathBuf>>,
    /// The files behind the menu's "Open Recent" (ADR 0114 Q4): item
    /// `verso-recent-file-<i>` opens `menu_recent_files[i]`.
    #[cfg(target_os = "macos")]
    menu_recent_files: Mutex<Vec<PathBuf>>,
    /// The menu's language, pushed by the UI with its own ("pt" or "en").
    menu_language: Mutex<String>,
    /// What the window pushed for the menu: its features, keys and the
    /// commands that can run now (`menu_spec::MenuState`).
    menu_state: Mutex<MenuState>,
    /// Set once the setup made the main window. On macOS the folder of
    /// `open -a Verso <folder>` arrives as an open event before the setup
    /// runs (tao hands `application:openURLs:` over before the launch
    /// ends): the main window, made next, opens it — no other window is
    /// made for it (`folder_handed`).
    started: std::sync::atomic::AtomicBool,
    /// "This app is a server" (ADR 0096), made on first use.
    pub(crate) local_server: local_server::LocalSlot,
    /// The embedded terminal's shells (ADR 0115).
    pub(crate) terminals: Arc<terminal::Terminals>,
}

impl App {
    /// The state before any folder is open; `initial` is what the command
    /// line named, if anything.
    #[must_use]
    pub fn new(initial: Option<PathBuf>) -> Self {
        // `verso-app <path>`: a Markdown file, or a data file (ADR 0114
        // items 6 and 32), is a loose file; anything else is opened as a
        // folder, and what is not one fails there, in words, as before.
        let (folders, files): (Vec<PathBuf>, Vec<PathBuf>) = initial
            .into_iter()
            .partition(|p| !verso_core::kind_of(p).opens_loose());
        Self {
            popouts: Mutex::new(std::collections::HashMap::new()),
            web_views: Mutex::new(std::collections::HashMap::new()),
            initial_folder: Mutex::new(folders.into_iter().collect()),
            initial_file: Mutex::new(files.into_iter().collect()),
            loose_window: Mutex::new(None),
            initial_server: Mutex::new(std::collections::VecDeque::new()),
            quitting: std::sync::atomic::AtomicBool::new(false),
            pending_servers: Mutex::new(std::collections::HashMap::new()),
            opening: Mutex::new(std::collections::HashSet::new()),
            service: Service::new(None),
            remotes: Mutex::new(std::collections::HashMap::new()),
            syncs: Mutex::new(std::collections::HashMap::new()),
            secrets: Arc::new(secrets::Keychain),
            pending_clouds: Mutex::new(std::collections::HashMap::new()),
            embed_origins: Mutex::new(std::collections::HashSet::new()),
            frame_verdicts: Mutex::new(std::collections::HashMap::new()),
            framed_origins: Mutex::new(std::collections::HashSet::new()),
            #[cfg(target_os = "macos")]
            menu_recents: Mutex::new(Vec::new()),
            #[cfg(target_os = "macos")]
            menu_recent_files: Mutex::new(Vec::new()),
            menu_language: Mutex::new("pt".to_owned()),
            menu_state: Mutex::new(MenuState::default()),
            started: std::sync::atomic::AtomicBool::new(false),
            local_server: local_server::LocalSlot::default(),
            terminals: Arc::default(),
        }
    }
}

fn failed(message: impl Into<String>) -> ContractError {
    let message = message.into();
    // The funnel for the host's own failures: what the window is about
    // to show for a moment, the log keeps (`log.rs`).
    log::write("ERROR", "host", &message);
    verso_service::failed(message)
}

/// The service's events as Tauri's: progress to the windows of its
/// folder, `folder-changed` once — every window listens to it, whatever
/// its label; `emit_to` a label also reaches every listener that listens
/// to all, so a loop over the windows delivered each batch once per
/// window to each of them. Web pages' views cannot listen
/// (capabilities/default.json).
struct TauriEvents<R: tauri::Runtime> {
    app: tauri::AppHandle<R>,
}

impl<R: tauri::Runtime> verso_service::Events for TauriEvents<R> {
    fn progress(&self, windows: &[String], progress: &IndexProgress) {
        for label in windows {
            let _ = self.app.emit_to(label.as_str(), "index-progress", progress);
        }
    }

    fn folder_changed(&self, _: &[String], changed: &FolderChanged) {
        let _ = self.app.emit("folder-changed", changed);
        // A synced folder's changes cross on this batch (ADR 0079 item 6).
        touched(
            &self.app,
            &changed.key,
            changed.changed.iter().chain(&changed.removed).cloned(),
        );
    }

    fn log(&self, level: &str, message: &str) {
        log::write(level, "host", message);
    }
}

/// The service hears this app from now on.
fn hear<R: tauri::Runtime>(app: &tauri::AppHandle<R>) {
    app.state::<App>()
        .service
        .set_events(Arc::new(TauriEvents { app: app.clone() }));
}

/// Run `f` on the folder this window shows (`Service::with`): a panic
/// inside the core is answered as `failed`, not propagated.
fn with<T, R: tauri::Runtime>(
    state: &State<'_, App>,
    window: &tauri::Window<R>,
    f: impl FnOnce(&mut Workspace) -> Result<T, OpError>,
) -> Result<T, ContractError> {
    state.service.with(window.label(), f)
}

/// Whether this window may open or switch its folder (ADR 0065): a window
/// of a folder (`main`, `window-N`) may, unless a note of its folder is
/// open in a window of its own and no other window shows that folder —
/// the note window names its note by a path of the folder it would lose.
fn may_switch<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    window: &tauri::Window<R>,
) -> Result<(), ContractError> {
    let me = window.label();
    if me != "main" && !me.starts_with("window-") {
        return Err(refused("only a window of the folder opens a folder"));
    }
    let clients = app.state::<App>().service.clients();
    let Some(mine) = clients.iter().find(|(l, _)| l == me).map(|(_, k)| k) else {
        return Ok(());
    };
    let shown_elsewhere = clients
        .iter()
        .any(|(label, key)| label != me && key == mine && !label.starts_with("note-"));
    let notes_open = clients.iter().any(|(label, key)| {
        key == mine && label.starts_with("note-") && app.get_window(label).is_some()
    });
    if notes_open && !shown_elsewhere {
        return Err(refused("close the note windows first"));
    }
    Ok(())
}

/// Open a folder off the event loop — opening indexes it, which can take
/// seconds on a large vault — and make it the session. `open` is given the
/// directory the indexes go to (`App::config`). The switch is checked
/// again once the folder is open: a note window may have opened while the
/// picker was up.
async fn install<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    window: &tauri::Window<R>,
    open: impl FnOnce(Option<&Path>) -> Result<Workspace, CoreError> + Send + 'static,
) -> Result<FolderInfo, ContractError> {
    // Until its folder is installed, this window is not empty for a folder
    // handed by a second launch (`folder_handed`), though no session names
    // it yet — whatever opens it: the command line's folder, the picker, a
    // reopened one. Unmarked on every way out.
    let _opening = Opening::mark(app, window.label());
    let service = Arc::clone(&app.state::<App>().service);
    let opener = window.label().to_owned();
    let opened = tauri::async_runtime::spawn_blocking(move || service.open(&opener, open))
        .await
        .map_err(|e| failed(e.to_string()))??;
    may_switch(app, window)?;
    // A window that showed a server's folder shows this computer's now.
    remote::release(app, window.label());
    let service = Arc::clone(&app.state::<App>().service);
    let (info, catch_up) = service.attach(window.label(), opened);
    // The folder it showed may be shown by no window now; the one it
    // shows syncs if it is set to (ADR 0079).
    settle(app);
    resume(app, &info.key);
    // A window is named after its folder (ADR 0065).
    let _ = window.set_title(&format!("{} — Verso", info.name));
    loose::left(app, window.label());
    // A batch that came while the folder was being opened found no session
    // to bring up to date; it runs now.
    if let Some(catch_up) = catch_up {
        let service = Arc::clone(&service);
        tauri::async_runtime::spawn_blocking(move || service.catch_up(&catch_up));
    }
    // Its bin is swept as it opens (ADR 0080 item 3), off the event loop.
    {
        let key = info.key.clone();
        tauri::async_runtime::spawn_blocking(move || trash::sweep_now(&service, &key));
    }
    // The folder just opened is the freshest recent: the menu learns.
    #[cfg(target_os = "macos")]
    refresh_menu(app);
    // The next start brings this window back (ADR 0065).
    session::remember(app);
    Ok(info)
}

/// Run the native folder picker and open what the user chose: the entry
/// edge, on this side of the contract (rule 4). `None` when the picker
/// was cancelled. The picker and the indexing run off the event loop.
#[tauri::command]
#[specta::specta]
async fn pick_folder<R: tauri::Runtime>(
    app: tauri::AppHandle<R>,
    window: tauri::Window<R>,
) -> Result<Option<FolderInfo>, ContractError> {
    may_switch(&app, &window)?;
    let (tx, mut rx) = tauri::async_runtime::channel(1);
    let parent = window.clone();
    app.dialog()
        .file()
        .set_parent(&parent)
        .pick_folder(move |picked| {
            let _ = tx.try_send(picked);
        });
    let picked = rx.recv().await.flatten();
    let Some(picked) = picked else {
        return Ok(None);
    };
    let path = picked.into_path().map_err(|e| failed(e.to_string()))?;
    install(&app, &window, move |config| Workspace::open(&path, config))
        .await
        .map(Some)
}

/// Open again a folder opened before, by the key `FolderInfo` carried:
/// `refused` when the key is not one this app issues (so it can never
/// name a path), `not_found` when no folder opened before has it or the
/// folder is gone.
#[tauri::command]
#[specta::specta]
async fn reopen_folder<R: tauri::Runtime>(
    app: tauri::AppHandle<R>,
    window: tauri::Window<R>,
    key: String,
) -> Result<FolderInfo, ContractError> {
    may_switch(&app, &window)?;
    install(&app, &window, move |config| Workspace::reopen(&key, config)).await
}

/// Open, once, what was handed to the app — a folder named on the command
/// line (`verso-app <folder>`) or, on macOS, sent by an open event
/// (`folder_handed`), or a Markdown file (ADR 0114: `Opened::File`);
/// `None` afterwards and when there was none. The UI calls it at
/// start-up, before falling back to the last folder it remembers, and
/// again when the host says a folder or a file was handed to the app while
/// it ran. The loose-files window takes files only, never a folder.
#[tauri::command]
#[specta::specta]
async fn open_initial<R: tauri::Runtime>(
    app: tauri::AppHandle<R>,
    window: tauri::Window<R>,
) -> Result<Option<Opened>, ContractError> {
    may_switch(&app, &window)?;
    let path = if loose::is_loose_window(&app, window.label()) {
        None
    } else {
        lock(&app.state::<App>().initial_folder).pop_front()
    };
    let Some(path) = path else {
        if let Some(file) = loose::open_initial_file(&app, &window).await {
            return file.map(Some);
        }
        // A server's folder the last session had open (`session::restore`).
        let server = lock(&app.state::<App>().initial_server).pop_front();
        if let Some((url, folder)) = server {
            let label = window.label().to_owned();
            let key = session::server_key(&url, &folder);
            let opened = remote::server_open(app.clone(), window, url, folder).await;
            if opened.is_err() {
                // Kept in the set: the server may be back by the next start.
                lock(&app.state::<App>().pending_servers).insert(label, key);
                session::remember(&app);
            }
            return opened.map(Some).map(|o| o.map(Opened::Folder));
        }
        // Told, but the folder was taken by another window: not opening.
        lock(&app.state::<App>().opening).remove(window.label());
        return Ok(None);
    };
    install(&app, &window, move |config| Workspace::open(&path, config))
        .await
        .map(|info| Some(Opened::Folder(info)))
}

