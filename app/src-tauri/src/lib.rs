/// The folder this window shows, for a window that joins a session (a
/// note in a window of its own, a window opened on the same folder) and
/// for a reload: `None` when it shows none (ADR 0065).
#[tauri::command]
#[specta::specta]
fn current_folder<R: tauri::Runtime>(
    window: tauri::Window<R>,
    state: State<'_, App>,
) -> Result<Option<FolderInfo>, ContractError> {
    Ok(lock(&state.sessions)
        .of(window.label())
        .map(|s| s.info.clone()))
}

/// The origins of embedded pages the user approved, replacing the list
/// as a whole. The UI keeps the list with its settings and pushes it
/// here; the navigation guard lets an app view's frames load exactly
/// these (ADR 0056, revised 2026-09-29).
#[tauri::command]
#[specta::specta]
fn set_embed_origins(state: State<'_, App>, origins: Vec<String>) -> Result<(), ContractError> {
    let normalized: std::collections::HashSet<String> = origins
        .iter()
        .filter_map(|o| reqwest::Url::parse(o).ok())
        .filter(|u| u.scheme() == "http" || u.scheme() == "https")
        .filter_map(|u| embed_origin_of(&u))
        .collect();
    *lock(&state.embed_origins) = normalized;
    Ok(())
}

/// A line from the window into the app's log: what `fail()` shows for a
/// moment there, and what the browser would otherwise swallow — a
/// script error, a rejected promise. The source is the window's, the
/// text is the window's; nothing else is added and nothing is sent
/// anywhere (`log.rs`).
#[tauri::command]
#[specta::specta]
fn log_write(level: String, message: String) -> Result<(), ContractError> {
    let level = match level.as_str() {
        "PANIC" | "ERROR" | "WARN" | "INFO" => level,
        _ => "ERROR".to_owned(),
    };
    log::write(&level, "window", &message);
    Ok(())
}

/// The end of the log and where it lives: what a bug report carries, so
/// the user can read it before it goes anywhere.
#[tauri::command]
#[specta::specta]
fn log_read() -> Result<String, ContractError> {
    // The report may be pasted somewhere public: the home directory is
    // the user's name, more often than not. It is `~` wherever it appears,
    // the log's own lines included; with no home known, the log is named
    // by its file alone, never by an absolute path (ADR 0026 rule 4).
    let home = std::env::var("HOME").unwrap_or_default();
    let hidden = |text: &str| {
        if home.len() > 1 {
            text.replace(&home, "~")
        } else {
            text.to_owned()
        }
    };
    let where_ = log::path().map_or_else(String::new, |p| {
        let shown = hidden(&p.display().to_string());
        if shown.starts_with('~') {
            shown
        } else {
            p.file_name()
                .map_or_else(String::new, |n| n.to_string_lossy().into_owned())
        }
    });
    let tail = hidden(&log::tail(16 * 1024));
    Ok(if where_.is_empty() {
        tail
    } else {
        format!("{where_}\n\n{tail}")
    })
}

