/// A note in a window of its own: the same UI, which asks which note
/// by its window's label.
#[tauri::command]
#[specta::specta]
fn open_window(
    app: tauri::AppHandle,
    state: State<'_, App>,
    path: String,
) -> Result<(), ContractError> {
    let n = POPOUTS.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let label = format!("note-{n}");
    let title = path
        .rsplit('/')
        .next()
        .unwrap_or(&path)
        .trim_end_matches(".md")
        .to_owned();
    state
        .popouts
        .lock()
        .map_err(|e| failed(e.to_string()))?
        .insert(label.clone(), path);
    tauri::WebviewWindowBuilder::new(&app, &label, tauri::WebviewUrl::App("index.html".into()))
        .title(title)
        .inner_size(920.0, 720.0)
        .min_inner_size(360.0, 400.0)
        .disable_drag_drop_handler()
        .build()
        .map_err(|e| failed(e.to_string()))?;
    Ok(())
}

/// Which note this window shows, when it is one popped out; `None` for
/// the main window.
#[tauri::command]
#[specta::specta]
fn popout_target(
    window: tauri::Window,
    state: State<'_, App>,
) -> Result<Option<String>, ContractError> {
    Ok(state
        .popouts
        .lock()
        .map_err(|e| failed(e.to_string()))?
        .get(window.label())
        .cloned())
}

/// The note goes back into the main window: the main window is told,
/// then this one closes.
#[tauri::command]
#[specta::specta]
fn return_to_main(
    app: tauri::AppHandle,
    window: tauri::Window,
    state: State<'_, App>,
    path: String,
) -> Result<(), ContractError> {
    use tauri::Emitter;
    app.emit_to("main", "open-note", path)
        .map_err(|e| failed(e.to_string()))?;
    state
        .popouts
        .lock()
        .map_err(|e| failed(e.to_string()))?
        .remove(window.label());
    window.close().map_err(|e| failed(e.to_string()))
}

/// The folder the command line asked for, once; `None` afterwards and
/// when there was none. The UI opens it instead of the last folder.
#[tauri::command]
#[specta::specta]
fn initial_folder(state: State<'_, App>) -> Result<Option<String>, ContractError> {
    Ok(state
        .initial_folder
        .lock()
        .map_err(|e| failed(e.to_string()))?
        .take())
}

/// Refresh the index from the folder: only what changed is re-read.
