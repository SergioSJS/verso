/// `%XX` sequences of a URL path back to bytes, then to text.
fn percent_decode(s: &str) -> String {
    let bytes = s.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%'
            && i + 2 < bytes.len()
            && let Ok(v) = u8::from_str_radix(&s[i + 1..i + 3], 16)
        {
            out.push(v);
            i += 3;
            continue;
        }
        out.push(bytes[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

fn mime_of(path: &str) -> &'static str {
    match path
        .rsplit('.')
        .next()
        .map(str::to_ascii_lowercase)
        .as_deref()
    {
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("gif") => "image/gif",
        Some("webp") => "image/webp",
        Some("svg") => "image/svg+xml",
        Some("bmp") => "image/bmp",
        Some("avif") => "image/avif",
        // The HTML-file viewer's page (review phase-2, reading 1, finding
        // 1): as a document, under `FILE_CSP`'s sandbox. Served as bytes,
        // `nosniff` kept the frame from showing it at all.
        Some("html" | "htm") => "text/html; charset=utf-8",
        Some("pdf") => "application/pdf",
        Some("mp3") => "audio/mpeg",
        Some("m4a") => "audio/mp4",
        Some("ogg") => "audio/ogg",
        Some("wav") => "audio/wav",
        Some("mp4") => "video/mp4",
        Some("webm") => "video/webm",
        _ => "application/octet-stream",
    }
}

/// Whether a web view of this app is one of its own windows' — the main
/// window, another window of the folder, or a note popped out — as opposed
/// to a web page (`web-*`).
fn is_app_view(label: &str) -> bool {
    label == "main" || label.starts_with("window-") || label.starts_with("note-")
}

/// What `verso://` answers to one request, apart from the transport: the
/// status, the headers, the body. Kept free of Tauri's types so the
/// rules are tested directly.
struct Served {
    status: u16,
    headers: Vec<(&'static str, String)>,
    body: Vec<u8>,
}

/// The policy every `verso://` response carries: whatever the file is,
/// a document made of it runs no script, submits no form and reaches
/// nothing but the folder's own files (SVG and HTML are active content;
/// review `docs/review/phase-2.md`, B1).
const FILE_CSP: &str = "sandbox; default-src 'none'; img-src verso: http://verso.localhost data:; media-src verso: http://verso.localhost; style-src 'unsafe-inline' verso: http://verso.localhost; font-src verso: http://verso.localhost data:";

/// The origins of the app's own pages, the only ones allowed to read a
/// response with `fetch` (the PDF reader): `tauri://localhost` on macOS
/// and Linux, `http(s)://tauri.localhost` on Windows.
fn is_app_origin(origin: &str) -> bool {
    matches!(
        origin,
        "tauri://localhost" | "http://tauri.localhost" | "https://tauri.localhost"
    )
}

fn serve(
    ws: Option<&mut Workspace>,
    requester: &str,
    relative: &str,
    origin: Option<&str>,
) -> Served {
    let mut headers = vec![
        ("Content-Security-Policy", FILE_CSP.to_owned()),
        ("X-Content-Type-Options", "nosniff".to_owned()),
        ("Cache-Control", "no-store".to_owned()),
    ];
    if let Some(o) = origin.filter(|o| is_app_origin(o)) {
        headers.push(("Access-Control-Allow-Origin", o.to_owned()));
        headers.push(("Vary", "Origin".to_owned()));
    }
    let refuse = |status: u16, why: &str, mut headers: Vec<(&'static str, String)>| {
        headers.push(("Content-Type", "text/plain; charset=utf-8".to_owned()));
        Served {
            status,
            headers,
            body: why.as_bytes().to_vec(),
        }
    };
    // A web page's view never reads the folder, whatever it asks for.
    if !is_app_view(requester) {
        return refuse(403, "not a view of this app", headers);
    }
    // A note's text crosses through `read_note`, with its revision;
    // never as a bare file.
    if relative.to_lowercase().ends_with(".md") {
        return refuse(403, "a note is read through read_note", headers);
    }
    let Some(ws) = ws else {
        return refuse(404, "no folder is open", headers);
    };
    // And judged again on the path as confinement reads it: `Nota.md/`
    // and `./Nota.md` name the note too.
    if ws
        .confined(relative)
        .is_ok_and(|key| key.to_lowercase().ends_with(".md"))
    {
        return refuse(403, "a note is read through read_note", headers);
    }
    match ws.read_file(relative) {
        Ok(bytes) => {
            headers.push(("Content-Type", mime_of(relative).to_owned()));
            Served {
                status: 200,
                headers,
                body: bytes,
            }
        }
        Err(e) => {
            let e = convert(e);
            let status = match e.kind {
                ErrorKind::NotFound | ErrorKind::Refused | ErrorKind::NoFolder => 404,
                _ => 500,
            };
            refuse(status, &e.message, headers)
        }
    }
}

/// The origin of a URL, in the form the approval list stores:
/// `scheme://host` with the port when it is not the scheme's default.
fn embed_origin_of(url: &reqwest::Url) -> Option<String> {
    let host = url.host_str()?;
    match url.port() {
        Some(p) => Some(format!("{}://{}:{}", url.scheme(), host.to_lowercase(), p)),
        None => Some(format!("{}://{}", url.scheme(), host.to_lowercase())),
    }
}

/// `verso://localhost/<relative path>`: a file of the folder that is not
/// a note — an image an embed names, a PDF, an HTML page shown without
/// scripts — read through the core, so the only door to the disk stays
/// `verso-fs` (ADR 0026 rule 5) and every path is confined. Only the
/// app's own views are answered, and only their origin may read a
/// response from script.
fn serve_file<R: tauri::Runtime>(
    ctx: tauri::UriSchemeContext<'_, R>,
    request: tauri::http::Request<Vec<u8>>,
    responder: tauri::UriSchemeResponder,
) {
    let relative = percent_decode(request.uri().path().trim_start_matches('/'));
    let origin = request
        .headers()
        .get("Origin")
        .and_then(|v| v.to_str().ok())
        .map(str::to_owned);
    let label = ctx.webview_label().to_owned();
    // A picture the window shows is the user opening it: one only in the
    // cloud is brought down first (ADR 0043, amended on 2026-09-30). A
    // thumbnail in a folder's view is not (`?thumb`): opening a folder
    // never pulls it from the cloud.
    let fetch = !request
        .uri()
        .query()
        .is_some_and(|q| q.split('&').any(|p| p == "thumb"));
    let app = ctx.app_handle().clone();
    // Off the main thread: a file is read, and may be downloaded.
    tauri::async_runtime::spawn_blocking(move || {
        let state = app.state::<App>();
        if fetch && is_app_view(&label) && !relative.to_lowercase().ends_with(".md") {
            let placeholder = {
                let mut guard = lock(&state.session);
                guard.as_mut().and_then(|s| {
                    let note = s
                        .workspace
                        .confined(&relative)
                        .is_ok_and(|key| key.to_lowercase().ends_with(".md"));
                    if note {
                        None
                    } else {
                        s.workspace.placeholder(&relative).ok().flatten()
                    }
                })
            };
            if let Some(Err(e)) = placeholder.map(|p| p.fetch()) {
                log::write(
                    "ERROR",
                    "host",
                    &format!("fetching {relative} from the cloud: {e}"),
                );
            }
        }
        let served = {
            let mut guard = lock(&state.session);
            serve(
                guard.as_mut().map(|s| &mut s.workspace),
                &label,
                &relative,
                origin.as_deref(),
            )
        };
        let mut response = tauri::http::Response::builder().status(served.status);
        for (name, value) in &served.headers {
            response = response.header(*name, value);
        }
        responder.respond(
            response
                .body(served.body)
                .unwrap_or_else(|_| tauri::http::Response::new(Vec::new())),
        );
    });
}

/// Open the window and serve it until it closes.
pub fn run(initial_folder: Option<PathBuf>) -> Result<(), Box<dyn std::error::Error>> {
    let commands = commands();
    let initial_folder = initial_folder.map(|p| std::path::absolute(&p).unwrap_or(p));
    let builder = tauri::Builder::default();
    #[cfg(target_os = "macos")]
    let builder = builder.menu(app_menu).on_menu_event(|app, event| {
        let id = event.id().as_ref();
        if id == QUIT {
            ask_windows_to_quit(app);
        } else if id == NEW_WINDOW {
            // With no folder open the new window offers the picker — the
            // blank window the menu promises.
            let _ = open_folder_window(app);
        } else if id == OPEN_FOLDER {
            let _ = app.emit_to("main", "menu-open-folder", ());
        } else if id == SETTINGS {
            let _ = app.emit_to("main", "menu-settings", ());
        } else if let Some(command) = id.strip_prefix(EDIT_PREFIX) {
            // Every window hears an event (see `folder-changed`): the label
            // says which one runs it. A web page — a window of its own, or
            // a site shown inside a window of the app — has none of the
            // app's script: the one with the focus runs the system's own
            // editing command, as the system's menu item ran it (decided on
            // 2026-10-01, review `board.md` §6 item 20).
            if let Some(w) = focused_window(app) {
                let edit = page_edit(command);
                let app_view = is_app_view(w.label());
                if app_view {
                    let _ = app.emit("menu-edit", (w.label().to_owned(), command.to_owned()));
                }
                for view in w.webviews() {
                    if !app_view || view.label() != w.label() {
                        let _ = view.eval(&edit);
                    }
                }
            }
        } else if id == DEVTOOLS {
            if let Some(w) = focused_window(app) {
                let _ = app.emit("menu-devtools", w.label().to_owned());
            }
        } else if id == CLOSE_TAB {
            // A window of the app runs what ⌘W is bound to there (its
            // "close tab"); a window that is only a web page has no tab,
            // and closes.
            if let Some(w) = focused_window(app) {
                if is_app_view(w.label()) {
                    let _ = app.emit("menu-close-tab", w.label().to_owned());
                } else {
                    let _ = w.close();
                }
            }
        } else if id == CLOSE_WINDOW {
            if let Some(w) = focused_window(app) {
                let _ = w.close();
            }
        } else if let Some(index) = id.strip_prefix(RECENT_PREFIX) {
            // The folder stays on this side; the window is told the same
            // way an `open -a Verso <folder>` event tells it.
            let folder = index
                .parse::<usize>()
                .ok()
                .and_then(|i| lock(&app.state::<App>().menu_recents).get(i).cloned());
            if let Some(folder) = folder {
                folder_handed(app, folder);
            }
        }
    });
    log::open();
    log::install_panic_hook();
    log::write(
        "INFO",
        "host",
        &format!(
            "started {} ({}) on {}",
            env!("CARGO_PKG_VERSION"),
            env!("VERSO_COMMIT"),
            std::env::consts::OS
        ),
    );
    builder
        .plugin(tauri_plugin_dialog::init())
        .plugin(navigation_guard())
        .register_asynchronous_uri_scheme_protocol("verso", serve_file)
        .manage(App::new(initial_folder))
        .invoke_handler(commands.invoke_handler())
        .build(context())?
        .run(on_event);
    Ok(())
}

/// A quit — ⌘Q, or the last window going — asks every window to save
/// its tabs first: each one saves, then closes itself, and the app exits
/// when none is left (the next request finds no window and goes through).
/// A page's own close handler never hears a quit, so without this a quit
/// lost what was typed since the last autosave. A window whose text could
/// not be saved stays open if the user keeps it.
fn on_event<R: tauri::Runtime>(app: &tauri::AppHandle<R>, event: tauri::RunEvent) {
    // Why the app goes, in the log: a quit asked for, each window that
    // closes, and the exit itself — an app that vanished otherwise leaves
    // no trace of which of them it was.
    match &event {
        tauri::RunEvent::ExitRequested { code, .. } => log::write(
            "INFO",
            "host",
            &format!(
                "exit requested (code {code:?}, {} window(s) open)",
                app.windows().len()
            ),
        ),
        tauri::RunEvent::WindowEvent {
            label,
            event: tauri::WindowEvent::Destroyed,
            ..
        } => log::write("INFO", "host", &format!("window closed: {label}")),
        tauri::RunEvent::Exit => log::write("INFO", "host", "exiting"),
        _ => {}
    }
    match event {
        tauri::RunEvent::ExitRequested {
            api, code: None, ..
        } if !app.windows().is_empty() => {
            api.prevent_exit();
            ask_windows_to_quit(app);
        }
        #[cfg(target_os = "macos")]
        tauri::RunEvent::Opened { urls } => {
            if let Some(folder) = urls.iter().find_map(|u| u.to_file_path().ok()) {
                folder_handed(app, folder);
            }
        }
        _ => {}
    }
}

/// macOS hands the app a folder by an open event — `open -a Verso
/// <folder>`, which is how `verso <folder>` starts the installed app —
/// both when it launches the app and when the app is already running; the
/// folder never reaches the command line, and before this it was lost on
/// a running app (`docs/review/phase-2.md`, reading 3, finding 20). It
/// takes the command line's place: the main window, if it is up, is told
/// to open it (`open_initial`, after saving its tabs), and one that starts
/// later opens it at start-up. What is not a folder fails there, as a
/// command-line argument would. Built for tests on every platform, so
/// the Linux runs check it too; only macOS sends the event.
#[cfg(any(target_os = "macos", test))]
fn folder_handed<R: tauri::Runtime>(app: &tauri::AppHandle<R>, folder: PathBuf) {
    *lock(&app.state::<App>().initial_folder) = Some(folder);
    if let Some(main) = app.get_window("main") {
        let _ = main.set_focus();
    }
    let _ = app.emit_to("main", "folder-handed", ());
}

/// Ask the app's own windows to save their tabs and close themselves;
/// with none left, exit. A window that shows a web page holds nothing to
/// save and never answers, so it is closed here: left open, it would keep
/// the app alive after its windows had gone.
fn ask_windows_to_quit<R: tauri::Runtime>(app: &tauri::AppHandle<R>) {
    let mut ours = false;
    for (label, window) in app.windows() {
        if is_app_view(&label) {
            ours = true;
        } else {
            let _ = window.destroy();
        }
    }
    if ours {
        let _ = app.emit("quit-requested", ());
    } else {
        app.exit(0);
    }
}

