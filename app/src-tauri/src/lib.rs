/// A window marked as opening a folder (`App::opening`) while it lives.
struct Opening<R: tauri::Runtime> {
    app: tauri::AppHandle<R>,
    label: String,
}

impl<R: tauri::Runtime> Opening<R> {
    fn mark(app: &tauri::AppHandle<R>, label: &str) -> Self {
        lock(&app.state::<App>().opening).insert(label.to_owned());
        Self {
            app: app.clone(),
            label: label.to_owned(),
        }
    }
}

impl<R: tauri::Runtime> Drop for Opening<R> {
    fn drop(&mut self) {
        lock(&self.app.state::<App>().opening).remove(&self.label);
    }
}

/// Open the window and serve it until it closes.
pub fn run(initial_folder: Option<PathBuf>) -> Result<(), Box<dyn std::error::Error>> {
    // Before any TLS: the sync's WebSocket, the server calls, the updater.
    verso_server::install_crypto_provider();
    let commands = commands();
    let initial_folder = initial_folder.map(|p| std::path::absolute(&p).unwrap_or(p));
    // First of the plugins, as the plugin asks: a second launch hands its
    // folder over and exits before anything else of it starts.
    let builder =
        tauri::Builder::default().plugin(tauri_plugin_single_instance::init(second_launch));
    // A web process that dies leaves the Linux window white for good: watch
    // each webview once, from its first page load (src/recover.rs).
    #[cfg(target_os = "linux")]
    let builder = builder.on_page_load(|webview, payload| {
        if payload.event() == tauri::webview::PageLoadEvent::Started {
            recover::hook(webview);
        }
    });
    #[cfg(target_os = "macos")]
    let builder = builder.menu(app_menu).on_menu_event(|app, event| {
        let id = event.id().as_ref();
        if id == QUIT {
            ask_windows_to_quit(app);
        } else if id == NEW_WINDOW {
            // A window with no folder, on the start page (ADR 0065).
            let _ = open_folder_window(app, None);
        } else if id == OPEN_FOLDER {
            let _ = app.emit("menu-open-folder", folder_window_in_focus(app));
        } else if id == OPEN_FILE {
            // File › Open File… (ADR 0114 item 20): the picker, then the
            // file handed over as a double-click is.
            let parent = focused_window(app);
            loose::pick_file_and_hand(app, parent.as_ref());
        } else if id == SETTINGS {
            let _ = app.emit("menu-settings", folder_window_in_focus(app));
        } else if let Some(command) = id.strip_prefix(EDIT_PREFIX) {
            // Every window hears an event (see `folder-changed`): the label
            // says which one runs it. A web page — a window of its own, or
            // a site shown inside a window of the app — has none of the
            // app's script: the one with the focus runs the system's own
            // editing command, as the system's menu item ran it (decided on
            // 2026-10-01, review `board.md` §6 item 20).
            if let Some(w) = focused_window(app) {
                let edit = page_edit(command);
                let app_view = is_app_view(w.label());
                if app_view {
                    let _ = app.emit("menu-edit", (w.label().to_owned(), command.to_owned()));
                }
                for view in w.webviews() {
                    if !app_view || view.label() != w.label() {
                        let _ = view.eval(&edit);
                    }
                }
            }
        } else if id == DEVTOOLS {
            if let Some(w) = focused_window(app) {
                let _ = app.emit("menu-devtools", w.label().to_owned());
            }
        } else if id == CLOSE_TAB {
            // A window of the app runs what ⌘W is bound to there (its
            // "close tab"); a window that is only a web page has no tab,
            // and closes.
            if let Some(w) = focused_window(app) {
                if is_app_view(w.label()) {
                    let _ = app.emit("menu-close-tab", w.label().to_owned());
                } else {
                    session::closing(w.label(), "the Close Tab menu item on a page window");
                    let _ = w.close();
                }
            }
        } else if id == CLOSE_WINDOW {
            if let Some(w) = focused_window(app) {
                session::closing(w.label(), "the Close Window menu item");
                let _ = w.close();
            }
        } else if let Some(command) = id.strip_prefix(menu_spec::COMMAND_PREFIX) {
            // An item of the window's own commands: the focused window
            // runs the same command the palette runs.
            if let Some(w) = focused_window(app)
                && is_app_view(w.label())
            {
                let _ = app.emit("menu-command", (w.label().to_owned(), command.to_owned()));
            }
        } else if let Some(index) = id.strip_prefix(RECENT_PREFIX) {
            // The folder stays on this side; the window is told the same
            // way an `open -a Verso <folder>` event tells it.
            let folder = index
                .parse::<usize>()
                .ok()
                .and_then(|i| lock(&app.state::<App>().menu_recents).get(i).cloned());
            if let Some(folder) = folder {
                folder_handed(app, folder);
            }
        } else if let Some(index) = id.strip_prefix(RECENT_FILE_PREFIX) {
            // A recent file (ADR 0114 Q4): handed over as a double-click is.
            let file = index
                .parse::<usize>()
                .ok()
                .and_then(|i| lock(&app.state::<App>().menu_recent_files).get(i).cloned());
            if let Some(file) = file {
                loose::path_handed(app, file);
            }
        }
    });
    log::open();
    // "This app is a server" says its life in the app's own log (ADR 0096
    // item 14): the server crate's lines, which go to standard error
    // where there is a terminal, come here too.
    verso_server::log::set_sink(Some(|level, message| log::write(level, "local", message)));
    log::install_panic_hook();
    log::write(
        "INFO",
        "host",
        &format!(
            "started {} ({}) on {}",
            env!("CARGO_PKG_VERSION"),
            env!("VERSO_COMMIT"),
            std::env::consts::OS
        ),
    );
    builder
        .setup(|app| {
            // Serving to a phone is off at every start unless the person
            // asked it to keep on (ADR 0096 item 1).
            local_server::auto_start(app.handle());
            // The window's data under the former identifier comes along,
            // before any window opens (ADR 0004, decided 2026-10-07).
            migrate_web_data(&app.config().identifier);
            hear(app.handle());
            // Each open folder's bin, swept once a day (ADR 0080 item 3).
            trash::start_daily(app.handle());
            // Each folder of this computer keeps its version history in
            // the configuration directory, named by this computer (ADR
            // 0091 item 8); the person's retention comes with the
            // window's settings (`set_history_days`).
            {
                let state = app.state::<App>();
                let name = device::name(state.service.config());
                state
                    .service
                    .keep_local_history(&name, verso_core::history::DEFAULT_DAYS);
            }
            // The main window is made here, not from the configuration
            // alone: it needs the download hook every window of the app
            // has (`on_download`).
            // Its size fits the screen it opens on (`fit_config`): a small
            // screen's work area caps it, a large one keeps the default.
            if let Some(config) = app.config().app.windows.iter().find(|w| w.label == "main") {
                let mut config = config.clone();
                fit_config(app.handle(), &mut config);
                open_frameless(
                    tauri::WebviewWindowBuilder::from_config(app.handle(), &config)?
                        .on_download(on_download),
                )?;
            }
            app.state::<App>()
                .started
                .store(true, std::sync::atomic::Ordering::SeqCst);
            // The folder windows the last session had open (ADR 0065).
            session::restore(app.handle());
            Ok(())
        })
        .plugin(tauri_plugin_dialog::init())
        // The system's notifications (ADR 0084 item 9): the window asks
        // for them, and only while it is not in front.
        .plugin(tauri_plugin_notification::init())
        .plugin(navigation_guard())
        .register_asynchronous_uri_scheme_protocol("verso", serve_file)
        .manage(App::new(initial_folder))
        .invoke_handler({
            // A window on a server's folder sends the folder's commands to
            // the server (remote.rs); every other goes to this app.
            let handler = commands.invoke_handler();
            move |invoke| match remote::forward(invoke).and_then(live_forward) {
                None => true,
                Some(invoke) => handler(invoke),
            }
        })
        .build(context())?
        .run(on_event);
    Ok(())
}

/// A quit — ⌘Q, or the last window going — asks every window to save
/// its tabs first: each one saves, then closes itself, and the app exits
/// when none is left (the next request finds no window and goes through).
/// A page's own close handler never hears a quit, so without this a quit
/// lost what was typed since the last autosave. A window whose text could
/// not be saved stays open if the user keeps it.
fn on_event<R: tauri::Runtime>(app: &tauri::AppHandle<R>, event: tauri::RunEvent) {
    // Why the app goes, in the log: a quit asked for, each window that
    // closes, and the exit itself — an app that vanished otherwise leaves
    // no trace of which of them it was.
    match &event {
        tauri::RunEvent::ExitRequested { code, .. } => log::write(
            "INFO",
            "host",
            &format!(
                "exit requested (code {code:?}, {} window(s) open)",
                app.windows().len()
            ),
        ),
        // Files dragged in from the system's file manager (T.11): the host
        // gets the paths, the window the names and where they fell.
        tauri::RunEvent::WindowEvent {
            label,
            event: tauri::WindowEvent::DragDrop(drag),
            ..
        } => files::dragged(app, label, drag),
        tauri::RunEvent::WindowEvent {
            label,
            event: tauri::WindowEvent::CloseRequested { .. },
            ..
        } => session::closing(
            label,
            "a close request (the frame's button or the system's)",
        ),
        tauri::RunEvent::WindowEvent {
            label,
            event: tauri::WindowEvent::Destroyed,
            ..
        } => {
            #[cfg(target_os = "linux")]
            recover::forget(label);
            {
                let state = app.state::<App>();
                let showed = state.service.folder_of(label).is_some()
                    || remote::of(app, label).is_some()
                    || lock(&state.pending_servers).contains_key(label);
                let quitting = state.quitting.load(std::sync::atomic::Ordering::SeqCst);
                log::write(
                    "INFO",
                    "host",
                    &session::close_line(label, showed, quitting),
                );
            }
            // A window the person closed does not come back at the next
            // start; one that closed with the app does (`session`).
            session::window_gone(app, label);
            // Its folder closes when no other window shows it (ADR 0065).
            app.state::<App>().service.release(label);
            // Its terminals end with it; a reload keeps them (ADR 0115 Q6).
            app.state::<App>().terminals.end_of(label);
            files::drop_picks(label);
            remote::release(app, label);
            loose::window_gone(app, label);
            settle(app);
            lock(&app.state::<App>().opening).remove(label);
        }
        tauri::RunEvent::Exit => {
            // The port closes and the goodbye is sent (ADR 0096 item 8).
            local_server::stop_on_exit(app);
            // No shell outlives the app (ADR 0115 item 13).
            app.state::<App>().terminals.end_all();
            log::write("INFO", "host", "exiting");
        }
        _ => {}
    }
    match event {
        tauri::RunEvent::ExitRequested {
            api, code: None, ..
        } if !app.windows().is_empty() => {
            api.prevent_exit();
            ask_windows_to_quit(app);
        }
        #[cfg(target_os = "macos")]
        tauri::RunEvent::Opened { urls } => {
            // Each file or folder in order (ADR 0114 item 6): several
            // files dropped on the icon at once each take their path.
            for path in urls.iter().filter_map(|u| u.to_file_path().ok()) {
                loose::path_handed(app, path);
            }
        }
        _ => {}
    }
}

/// Ask the app's own windows to save their tabs and close themselves;
/// with none left, exit. A window that shows a web page holds nothing to
/// save and never answers, so it is closed here: left open, it would keep
/// the app alive after its windows had gone.
fn ask_windows_to_quit<R: tauri::Runtime>(app: &tauri::AppHandle<R>) {
    session::quitting(app);
    let mut ours = false;
    for (label, window) in app.windows() {
        if is_app_view(&label) {
            ours = true;
        } else {
            let _ = window.destroy();
        }
    }
    if ours {
        let _ = app.emit("quit-requested", ());
    } else {
        app.exit(0);
    }
}

