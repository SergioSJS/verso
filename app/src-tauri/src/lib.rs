/// What this side can do (ADR 0027; ADR 0076 item 11): the desktop app,
/// with a folder on this computer, does everything the window offers.
// And, while the folder syncs with its link up, it edits its notes with the
// people in the server's rooms, as far as the link says (ADR 0082 item 3).
// Not in the doc comment: that is the bindings', whose hash is the
// contract's version, and this answer changes no type (item 3).
#[tauri::command]
#[specta::specta]
fn capabilities<R: tauri::Runtime>(
    app: tauri::AppHandle<R>,
    window: tauri::Window<R>,
) -> Result<Capabilities, ContractError> {
    let live = live_latency(&app, window.label());
    let mut can = vec![
        Can::Write,
        Can::Reveal,
        Can::CopyPath,
        Can::Windows,
        Can::WebViews,
        Can::Agents,
        Can::Updates,
        Can::Devtools,
        Can::LocalFolders,
    ];
    if live.is_some() {
        can.push(Can::Collab);
    }
    // A window of files without a folder has no index, no tree, no bin, no
    // sync (ADR 0114 items 18 and 25); every other window shows a folder.
    if app.state::<App>().service.is_loose(window.label()) {
        can.retain(|c| !matches!(c, Can::Reveal | Can::CopyPath));
    } else {
        can.extend_from_slice(Can::FOLDER);
        // A shell of this computer (ADR 0115 item 6): never in a window of
        // files opened without their folder (ADR 0114 item 9).
        can.push(Can::Terminal);
    }
    // A folder of this computer alone is the person's own: no seat to tell.
    // A synced one carries the server's answer for it (ADR 0113 S8), the
    // last one while the server is out of reach.
    let access = sync_commands::synced_of(&app, window.label())
        .and_then(|s| s.seat())
        .and_then(|v| serde_json::from_value(v).ok());
    Ok(Capabilities {
        host: Host::Desktop,
        can,
        latency_ms: live,
        access,
    })
}

