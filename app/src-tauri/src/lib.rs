//! The desktop shell (Phase 2, item 2.2, walking skeleton): a Tauri v2
//! window whose only way to the notes is `verso-core`, through the
//! contract (`verso-contract`, ADR 0026). Nothing here reads a file and
//! no Tauri fs plugin is enabled (rule 5). Read-only for now: it opens a
//! folder, indexes it, lists the notes, shows one with its headings and
//! `^id` blocks, searches, and lists links and backlinks (items 2.3 and
//! 2.5; 2.4, the editor, comes after). The folder's path is the one
//! string that crosses, at the entry edge (rule 4); every note is named
//! by its path relative to the folder, and every path the UI sends is
//! confined by the core.
//!
//! The TypeScript bindings — types and command signatures — are
//! generated by tauri-specta from the commands below into
//! `app/ui/src/bindings.ts` (`verso-app --export-bindings`; ADR 0038,
//! decided 2026-09-22) and checked in CI, so rule 3 stays a rule.

use std::path::Path;
use std::sync::Mutex;

use tauri::{Manager, State};
use verso_contract::{
    Backlink, Block, ContractError, ErrorKind, FolderInfo, Heading, Hit, IndexSummary, Link,
    NoteText, Property, Written,
};
use verso_core::{CoreError, ReadError, Workspace, WriteError};

/// The one open folder, or none yet. One mutex: two commands never
/// interleave on the index.
pub struct App {
    workspace: Mutex<Option<Workspace>>,
}

fn convert(e: CoreError) -> ContractError {
    let kind = match &e {
        CoreError::Confined(_) => ErrorKind::Refused,
        CoreError::Read(ReadError::Unavailable) => ErrorKind::Unavailable,
        CoreError::Read(ReadError::Io(io)) if io.kind() == std::io::ErrorKind::NotFound => {
            ErrorKind::NotFound
        }
        CoreError::Write(WriteError::Changed { .. }) => ErrorKind::Changed,
        CoreError::Write(WriteError::Placeholder) => ErrorKind::Unavailable,
        _ => ErrorKind::Failed,
    };
    ContractError {
        kind,
        message: e.to_string(),
    }
}

fn failed(message: impl Into<String>) -> ContractError {
    ContractError {
        kind: ErrorKind::Failed,
        message: message.into(),
    }
}

fn no_folder() -> ContractError {
    ContractError {
        kind: ErrorKind::NoFolder,
        message: "no folder is open".to_owned(),
    }
}

fn count(n: usize) -> u32 {
    u32::try_from(n).unwrap_or(u32::MAX)
}

fn summary(r: &verso_core::IndexReport) -> IndexSummary {
    IndexSummary {
        indexed: count(r.indexed),
        unchanged: count(r.unchanged),
        removed: count(r.removed),
        placeholders: count(r.placeholders),
        problems: r.problems.iter().map(|p| format!("{p:?}")).collect(),
    }
}

/// Run `f` on the open workspace.
fn with<T>(
    state: &State<'_, App>,
    f: impl FnOnce(&mut Workspace) -> Result<T, CoreError>,
) -> Result<T, ContractError> {
    let mut guard = state.workspace.lock().map_err(|e| failed(e.to_string()))?;
    let ws = guard.as_mut().ok_or_else(no_folder)?;
    f(ws).map_err(convert)
}

/// Open a folder and bring its index up to date. The one command that
/// takes a path to a folder: the entry edge.
#[tauri::command]
#[specta::specta]
fn open_folder(state: State<'_, App>, path: String) -> Result<FolderInfo, ContractError> {
    let mut ws = Workspace::open(Path::new(&path), None).map_err(convert)?;
    let report = ws.index().map_err(convert)?;
    let info = FolderInfo {
        folder: ws.folder().to_string_lossy().into_owned(),
        index: summary(&report),
    };
    *state.workspace.lock().map_err(|e| failed(e.to_string()))? = Some(ws);
    Ok(info)
}

/// Every note the index knows, by path relative to the folder.
#[tauri::command]
#[specta::specta]
fn list_notes(state: State<'_, App>) -> Result<Vec<String>, ContractError> {
    with(&state, |ws| ws.notes())
}

/// A note's text as it is on disk, with what the index knows of it.
#[tauri::command]
#[specta::specta]
fn read_note(state: State<'_, App>, path: String) -> Result<NoteText, ContractError> {
    with(&state, |ws| ws.read_note(&path)).map(note_out)
}

fn note_out(t: verso_core::NoteText) -> NoteText {
    NoteText {
        path: t.path,
        lines: t.lines,
        html: t.html,
        properties: t
            .properties
            .into_iter()
            .map(|(key, value)| Property { key, value })
            .collect(),
        text: t.text,
        revision: t.revision,
        headings: t
            .headings
            .into_iter()
            .map(|h| Heading {
                level: h.level,
                text: h.text,
                line: h.line,
                col: h.col,
            })
            .collect(),
        blocks: t
            .blocks
            .into_iter()
            .map(|b| Block {
                id: b.id,
                line: b.line,
                col: b.col,
            })
            .collect(),
        stale: t.stale,
        unverified: t.unverified,
    }
}

/// Full-text search: every word must occur, accents and case ignored.
#[tauri::command]
#[specta::specta]
fn search(state: State<'_, App>, words: String, limit: u32) -> Result<Vec<Hit>, ContractError> {
    with(&state, |ws| {
        Ok(ws
            .search(&words, usize::try_from(limit.clamp(1, 200)).unwrap_or(20))?
            .into_iter()
            .map(|h| Hit {
                path: h.path,
                snippet: h.snippet,
            })
            .collect())
    })
}

/// The links a note makes; empty when the index does not know it.
#[tauri::command]
#[specta::specta]
fn links(state: State<'_, App>, path: String) -> Result<Vec<Link>, ContractError> {
    with(&state, |ws| {
        Ok(ws
            .links(&path)?
            .unwrap_or_default()
            .into_iter()
            .map(|l| Link {
                target: l.target,
                resolved: l.resolved,
                embed: l.embed,
                heading: l.heading,
                block: l.block,
                alias: l.alias,
                line: l.line,
                col: l.col,
            })
            .collect())
    })
}

/// The notes that link to this one; empty when the index does not know it.
#[tauri::command]
#[specta::specta]
fn backlinks(state: State<'_, App>, path: String) -> Result<Vec<Backlink>, ContractError> {
    with(&state, |ws| {
        Ok(ws
            .backlinks(&path)?
            .unwrap_or_default()
            .into_iter()
            .map(|b| Backlink {
                from: b.from,
                target: b.target,
                embed: b.embed,
                line: b.line,
                col: b.col,
            })
            .collect())
    })
}

/// Write a note's text over the revision that was read — atomically, no
/// normalization — and index it. `changed` when the file moved on
/// meanwhile: nothing written, read again and show the diff (invariant 11).
#[tauri::command]
#[specta::specta]
fn write_note(
    state: State<'_, App>,
    path: String,
    text: String,
    revision: String,
) -> Result<Written, ContractError> {
    with(&state, |ws| ws.write_note(&path, &text, &revision)).map(|w| Written {
        note: note_out(w.note),
        warnings: w.warnings,
    })
}

/// The file an embed names (`![[mapa.png]]`), relative to the folder, or
/// none. The UI then loads it through the `verso://` protocol below.
#[tauri::command]
#[specta::specta]
fn resolve_attachment(
    state: State<'_, App>,
    target: String,
) -> Result<Option<String>, ContractError> {
    with(&state, |ws| Ok(ws.resolve_file(&target)))
}

/// Refresh the index from the folder: only what changed is re-read.
#[tauri::command]
#[specta::specta]
fn reindex(state: State<'_, App>) -> Result<IndexSummary, ContractError> {
    with(&state, |ws| Ok(summary(&ws.index()?)))
}

/// The commands, once, for the handler and for the bindings.
fn commands() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new().commands(tauri_specta::collect_commands![
        open_folder,
        list_notes,
        read_note,
        search,
        links,
        backlinks,
        write_note,
        resolve_attachment,
        reindex
    ])
}

/// Write the TypeScript bindings (types and command signatures) to
/// `path`. CI checks the committed file is this output (ADR 0029).
pub fn export_bindings(path: &Path) -> Result<(), Box<dyn std::error::Error>> {
    commands().export(
        specta_typescript::Typescript::default()
            .header("// Generated by `verso-app --export-bindings` from crates/verso-contract and\n// app/src-tauri (ADR 0026 rule 3, ADR 0038). Do not edit: regenerate."),
        path,
    )?;
    Ok(())
}

/// `%XX` sequences of a URL path back to bytes, then to text.
fn percent_decode(s: &str) -> String {
    let bytes = s.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%'
            && i + 2 < bytes.len()
            && let Ok(v) = u8::from_str_radix(&s[i + 1..i + 3], 16)
        {
            out.push(v);
            i += 3;
            continue;
        }
        out.push(bytes[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

fn mime_of(path: &str) -> &'static str {
    match path
        .rsplit('.')
        .next()
        .map(str::to_ascii_lowercase)
        .as_deref()
    {
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("gif") => "image/gif",
        Some("webp") => "image/webp",
        Some("svg") => "image/svg+xml",
        Some("bmp") => "image/bmp",
        Some("avif") => "image/avif",
        Some("pdf") => "application/pdf",
        Some("mp3") => "audio/mpeg",
        Some("m4a") => "audio/mp4",
        Some("ogg") => "audio/ogg",
        Some("wav") => "audio/wav",
        Some("mp4") => "video/mp4",
        Some("webm") => "video/webm",
        _ => "application/octet-stream",
    }
}

/// `verso://localhost/<relative path>`: a file of the folder for the
/// preview — an image an embed names — read through the core, so the
/// only door to the disk stays `verso-fs` (ADR 0026 rule 5) and every
/// path is confined. Never a note's text: that is `read_note`'s.
fn serve_file(
    ctx: tauri::UriSchemeContext<'_, tauri::Wry>,
    request: tauri::http::Request<Vec<u8>>,
) -> tauri::http::Response<std::borrow::Cow<'static, [u8]>> {
    let relative = percent_decode(request.uri().path().trim_start_matches('/'));
    let answer = ctx
        .app_handle()
        .state::<App>()
        .workspace
        .lock()
        .map_err(|e| failed(e.to_string()))
        .and_then(|mut guard| {
            let ws = guard.as_mut().ok_or_else(no_folder)?;
            ws.read_file(&relative).map_err(convert)
        });
    let (status, mime, body): (u16, &str, Vec<u8>) = match answer {
        Ok(bytes) => (200, mime_of(&relative), bytes),
        Err(e) => {
            let status = match e.kind {
                ErrorKind::NotFound | ErrorKind::Refused | ErrorKind::NoFolder => 404,
                _ => 500,
            };
            (status, "text/plain; charset=utf-8", e.message.into_bytes())
        }
    };
    let body: std::borrow::Cow<'static, [u8]> = std::borrow::Cow::Owned(body);
    tauri::http::Response::builder()
        .status(status)
        .header("Content-Type", mime)
        .body(body)
        .unwrap_or_else(|_| tauri::http::Response::new(std::borrow::Cow::Owned(Vec::new())))
}

/// Open the window and serve it until it closes.
pub fn run() -> Result<(), Box<dyn std::error::Error>> {
    let commands = commands();
    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .register_uri_scheme_protocol("verso", serve_file)
        .manage(App {
            workspace: Mutex::new(None),
        })
        .invoke_handler(commands.invoke_handler())
        .run(tauri::generate_context!())?;
    Ok(())
}
