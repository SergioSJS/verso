/// Open the window and serve it until it closes.
pub fn run(initial_folder: Option<PathBuf>) -> Result<(), Box<dyn std::error::Error>> {
    let commands = commands();
    let initial_folder = initial_folder.map(|p| std::path::absolute(&p).unwrap_or(p));
    let builder = tauri::Builder::default();
    #[cfg(target_os = "macos")]
    let builder = builder.menu(app_menu).on_menu_event(|app, event| {
        let id = event.id().as_ref();
        if id == QUIT {
            ask_windows_to_quit(app);
        } else if id == NEW_WINDOW {
            // A window with no folder, on the start page (ADR 0065).
            let _ = open_folder_window(app, None);
        } else if id == OPEN_FOLDER {
            let _ = app.emit("menu-open-folder", folder_window_in_focus(app));
        } else if id == SETTINGS {
            let _ = app.emit("menu-settings", folder_window_in_focus(app));
        } else if let Some(command) = id.strip_prefix(EDIT_PREFIX) {
            // Every window hears an event (see `folder-changed`): the label
            // says which one runs it. A web page — a window of its own, or
            // a site shown inside a window of the app — has none of the
            // app's script: the one with the focus runs the system's own
            // editing command, as the system's menu item ran it (decided on
            // 2026-10-01, review `board.md` §6 item 20).
            if let Some(w) = focused_window(app) {
                let edit = page_edit(command);
                let app_view = is_app_view(w.label());
                if app_view {
                    let _ = app.emit("menu-edit", (w.label().to_owned(), command.to_owned()));
                }
                for view in w.webviews() {
                    if !app_view || view.label() != w.label() {
                        let _ = view.eval(&edit);
                    }
                }
            }
        } else if id == DEVTOOLS {
            if let Some(w) = focused_window(app) {
                let _ = app.emit("menu-devtools", w.label().to_owned());
            }
        } else if id == CLOSE_TAB {
            // A window of the app runs what ⌘W is bound to there (its
            // "close tab"); a window that is only a web page has no tab,
            // and closes.
            if let Some(w) = focused_window(app) {
                if is_app_view(w.label()) {
                    let _ = app.emit("menu-close-tab", w.label().to_owned());
                } else {
                    let _ = w.close();
                }
            }
        } else if id == CLOSE_WINDOW {
            if let Some(w) = focused_window(app) {
                let _ = w.close();
            }
        } else if let Some(index) = id.strip_prefix(RECENT_PREFIX) {
            // The folder stays on this side; the window is told the same
            // way an `open -a Verso <folder>` event tells it.
            let folder = index
                .parse::<usize>()
                .ok()
                .and_then(|i| lock(&app.state::<App>().menu_recents).get(i).cloned());
            if let Some(folder) = folder {
                folder_handed(app, folder);
            }
        }
    });
    log::open();
    log::install_panic_hook();
    log::write(
        "INFO",
        "host",
        &format!(
            "started {} ({}) on {}",
            env!("CARGO_PKG_VERSION"),
            env!("VERSO_COMMIT"),
            std::env::consts::OS
        ),
    );
    builder
        .setup(|app| {
            // The window's data under the former identifier comes along,
            // before any window opens (ADR 0004, decided 2026-10-07).
            migrate_web_data(&app.config().identifier);
            // The main window is made here, not from the configuration
            // alone: it needs the download hook every window of the app
            // has (`on_download`).
            if let Some(config) = app.config().app.windows.iter().find(|w| w.label == "main") {
                tauri::WebviewWindowBuilder::from_config(app.handle(), config)?
                    .on_download(on_download)
                    .build()?;
            }
            Ok(())
        })
        .plugin(tauri_plugin_dialog::init())
        .plugin(navigation_guard())
        .register_asynchronous_uri_scheme_protocol("verso", serve_file)
        .manage(App::new(initial_folder))
        .invoke_handler(commands.invoke_handler())
        .build(context())?
        .run(on_event);
    Ok(())
}

/// A quit — ⌘Q, or the last window going — asks every window to save
/// its tabs first: each one saves, then closes itself, and the app exits
/// when none is left (the next request finds no window and goes through).
/// A page's own close handler never hears a quit, so without this a quit
/// lost what was typed since the last autosave. A window whose text could
/// not be saved stays open if the user keeps it.
fn on_event<R: tauri::Runtime>(app: &tauri::AppHandle<R>, event: tauri::RunEvent) {
    // Why the app goes, in the log: a quit asked for, each window that
    // closes, and the exit itself — an app that vanished otherwise leaves
    // no trace of which of them it was.
    match &event {
        tauri::RunEvent::ExitRequested { code, .. } => log::write(
            "INFO",
            "host",
            &format!(
                "exit requested (code {code:?}, {} window(s) open)",
                app.windows().len()
            ),
        ),
        tauri::RunEvent::WindowEvent {
            label,
            event: tauri::WindowEvent::Destroyed,
            ..
        } => {
            log::write("INFO", "host", &format!("window closed: {label}"));
            // Its folder closes when no other window shows it (ADR 0065).
            lock(&app.state::<App>().sessions).release(label);
        }
        tauri::RunEvent::Exit => log::write("INFO", "host", "exiting"),
        _ => {}
    }
    match event {
        tauri::RunEvent::ExitRequested {
            api, code: None, ..
        } if !app.windows().is_empty() => {
            api.prevent_exit();
            ask_windows_to_quit(app);
        }
        #[cfg(target_os = "macos")]
        tauri::RunEvent::Opened { urls } => {
            if let Some(folder) = urls.iter().find_map(|u| u.to_file_path().ok()) {
                folder_handed(app, folder);
            }
        }
        _ => {}
    }
}

/// macOS hands the app a folder by an open event — `open -a Verso
/// <folder>`, which is how `verso <folder>` starts the installed app —
/// both when it launches the app and when the app is already running; the
/// folder never reaches the command line, and before this it was lost on
/// a running app (`docs/review/phase-2.md`, reading 3, finding 20). It
/// takes the command line's place: the main window, if it is up, is told
/// to open it (`open_initial`, after saving its tabs), and one that starts
/// later opens it at start-up. What is not a folder fails there, as a
/// command-line argument would. Built for tests on every platform, so
/// the Linux runs check it too; only macOS sends the event.
#[cfg(any(target_os = "macos", test))]
fn folder_handed<R: tauri::Runtime>(app: &tauri::AppHandle<R>, folder: PathBuf) {
    *lock(&app.state::<App>().initial_folder) = Some(folder);
    // A window of the app that shows no folder takes it; with none, a new
    // window does, which opens it as it starts (ADR 0065).
    let empty = {
        let state = app.state::<App>();
        let sessions = lock(&state.sessions);
        let mut labels: Vec<String> = app
            .windows()
            .into_keys()
            .filter(|l| {
                (l == "main" || l.starts_with("window-")) && !sessions.windows.contains_key(l)
            })
            .collect();
        labels.sort_by_key(|l| (l != "main", l.clone()));
        labels.into_iter().next()
    };
    match empty {
        Some(label) => {
            if let Some(w) = app.get_window(&label) {
                let _ = w.set_focus();
            }
            let _ = app.emit("folder-handed", label);
        }
        None => {
            let _ = open_folder_window(app, None);
        }
    }
}

/// The window of a folder that has the focus, for the menu's items that
/// act on one: the main window when none of them has it.
#[cfg(target_os = "macos")]
fn folder_window_in_focus<R: tauri::Runtime>(app: &tauri::AppHandle<R>) -> String {
    focused_window(app)
        .map(|w| w.label().to_owned())
        .filter(|l| l == "main" || l.starts_with("window-"))
        .unwrap_or_else(|| "main".to_owned())
}

/// Ask the app's own windows to save their tabs and close themselves;
/// with none left, exit. A window that shows a web page holds nothing to
/// save and never answers, so it is closed here: left open, it would keep
/// the app alive after its windows had gone.
fn ask_windows_to_quit<R: tauri::Runtime>(app: &tauri::AppHandle<R>) {
    let mut ours = false;
    for (label, window) in app.windows() {
        if is_app_view(&label) {
            ours = true;
        } else {
            let _ = window.destroy();
        }
    }
    if ours {
        let _ = app.emit("quit-requested", ());
    } else {
        app.exit(0);
    }
}

