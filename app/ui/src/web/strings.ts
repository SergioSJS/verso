let current: Lang = navigator.language.toLowerCase().startsWith("pt") ? "pt" : "en";

export function setLang(lang: string | undefined): void {
  if (lang === "pt" || lang === "en") current = lang;
  document.documentElement.lang = current === "pt" ? "pt-BR" : "en";
}

export function lang(): Lang {
  return current;
}

export function w(): WebStrings {
  return current === "pt" ? pt : en;
}

/** A size in bytes, as a person reads it. */
export function bytes(n: number): string {
  const units = ["B", "KB", "MB", "GB", "TB"];
  let v = n;
  let i = 0;
  while (v >= 1024 && i < units.length - 1) {
    v /= 1024;
    i++;
  }
  return `${v.toLocaleString(current === "pt" ? "pt-BR" : "en", { maximumFractionDigits: i ? 1 : 0 })} ${units[i]}`;
}

/** A moment, as a person reads it. */
export function when(seconds: number): string {
  return new Date(seconds * 1000).toLocaleString(current === "pt" ? "pt-BR" : "en");
}

export function roleName(role: string): string {
  const s = w();
  return role === "owner" ? s.roleOwner : role === "editor" ? s.roleEditor : s.roleReader;
}
