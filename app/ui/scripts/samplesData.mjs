#!/usr/bin/env node
// Builds src/statblock/builtin/samplesData.ts from builtin/samples/*.yaml,
// which stay the source of truth: one short sample statblock per built-in
// layout, for the editor's preview and the tutorial (ADR 0099 item 6). The
// window bundles the YAML as strings; `--check` fails when the module is not
// what the YAML would generate.
//   node scripts/samplesData.mjs          write the module
//   node scripts/samplesData.mjs --check  fail if it is stale

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = new URL("../src/statblock/builtin/samples/", import.meta.url);
const out = new URL("../src/statblock/builtin/samplesData.ts", import.meta.url);

export function build() {
  const names = readdirSync(dir).filter((n) => n.endsWith(".yaml")).sort();
  let ts = `// Generated by scripts/samplesData.mjs from builtin/samples/*.yaml — do not edit.
// A short sample statblock per built-in layout (invented names; no book's
// text), as the text of each YAML file, keyed by the layout's id.

export const SAMPLE_YAML: Readonly<Record<string, string>> = {
`;
  for (const n of names) ts += `  ${JSON.stringify(n.replace(/\.yaml$/, ""))}: ${JSON.stringify(readFileSync(new URL(n, dir), "utf8"))},\n`;
  return ts + "};\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const ts = build();
  if (process.argv.includes("--check")) {
    let now = "";
    try { now = readFileSync(out, "utf8"); } catch {}
    if (now !== ts) {
      console.error("samplesData.ts is stale: run `node scripts/samplesData.mjs` in app/ui");
      process.exit(1);
    }
  } else writeFileSync(out, ts);
}
