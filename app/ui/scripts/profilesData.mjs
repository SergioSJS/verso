#!/usr/bin/env node
// Builds src/dice/rolai/profilesData.ts from src/dice/rolai/profiles/*.yaml,
// which stay the source of truth (ADR 0088 item 5). The window bundles the
// YAML as strings; `--check` fails when the module is not what the YAML
// would generate.
//   node scripts/profilesData.mjs          write the module
//   node scripts/profilesData.mjs --check  fail if it is stale

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = new URL("../src/dice/rolai/profiles/", import.meta.url);
const out = new URL("../src/dice/rolai/profilesData.ts", import.meta.url);

export function build() {
  const names = readdirSync(dir).filter((n) => n.endsWith(".yaml")).sort();
  let ts = `// Generated by scripts/profilesData.mjs from profiles/*.yaml — do not edit.
// Rolai's system profiles (MIT, see LICENSE), as the text of each YAML file,
// keyed by file name without the extension.

export const PROFILE_YAML: Readonly<Record<string, string>> = {
`;
  for (const n of names) ts += `  ${JSON.stringify(n.replace(/\.yaml$/, ""))}: ${JSON.stringify(readFileSync(new URL(n, dir), "utf8"))},\n`;
  return ts + "};\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const ts = build();
  if (process.argv.includes("--check")) {
    let now = "";
    try { now = readFileSync(out, "utf8"); } catch {}
    if (now !== ts) {
      console.error("profilesData.ts is stale: run `node scripts/profilesData.mjs` in app/ui");
      process.exit(1);
    }
  } else writeFileSync(out, ts);
}
